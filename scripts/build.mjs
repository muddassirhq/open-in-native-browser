// Generates src/index.js (CommonJS) and dist/auto.global.js (script-tag build)
// from the single source of truth, src/index.mjs. No dependencies.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const src = readFileSync(join(root, 'src/index.mjs'), 'utf8');
const [core] = src.split('// @@EXPORTS');
if (!core || core === src) throw new Error('Missing "// @@EXPORTS" marker in src/index.mjs');

const banner = `/*! open-in-native-browser v${pkg.version} | MIT | https://github.com/muddassirhq/open-in-native-browser */\n`;
const note = '// GENERATED by scripts/build.mjs from src/index.mjs — edit that file, not this one.\n';

const cjs = banner + note + core +
  'module.exports = OpenInNativeBrowser;\n' +
  'module.exports.default = OpenInNativeBrowser;\n';
writeFileSync(join(root, 'src/index.js'), cjs);

const indented = core.split('\n').map((l) => (l ? '  ' + l : l)).join('\n');
const globalBuild = banner + note +
`/*
 * Script-tag build: attaches window.OpenInNativeBrowser and, unless
 * window.OPEN_IN_NATIVE_BROWSER_NO_AUTOINIT is true, runs
 * init(window.OPEN_IN_NATIVE_BROWSER_OPTIONS) immediately so the handoff
 * happens before the page finishes loading. The banner waits for <body>.
 */
(function (window, document) {
  'use strict';
${indented}
  window.OpenInNativeBrowser = OpenInNativeBrowser;
  if (!window.OPEN_IN_NATIVE_BROWSER_NO_AUTOINIT) {
    init(window.OPEN_IN_NATIVE_BROWSER_OPTIONS || {});
  }
})(window, document);
`;
mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/auto.global.js'), globalBuild);

console.log('built src/index.js and dist/auto.global.js');
